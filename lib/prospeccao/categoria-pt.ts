/**
 * Minúsculas + sem acento: "Mecânica" e "mecanica" são a mesma busca, e
 * "Oficina Mecânica" também. Sem isto, o operador digita "mecanica" (sem o
 * acento, porque é mais fácil no teclado) e não acha nada.
 */
export function semAcento(v: string): string {
  return v
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

/**
 * O rótulo em português de uma categoria gravada.
 *
 * Categoria fora da tabela DEVOLVE O PRÓPRIO VALOR, sem erro e sem exception.
 * Duas razones, e as duas importam:
 *
 * 1. Amanhã o Google acrescenta categorias. Um `throw` aqui levaria a tela
 *    inteira de Empresas junto — e o filtro é presentation, não o dado.
 * 2. Cache de tradução não é cache de verdade: o valor gravado pode ter vindo
 *    de outra origem, de um import manual, de uma planilha do dono.
 *
 * Traduzir errado é tolerável; esconder o filtro não é.
 */
export function traduzirCategoria(gravada: string): string {
  return CATEGORIA_PT[gravada] ?? gravada;
}

/**
 * AS CATEGORIAS QUE UM TERMO EM PORTUGUÊS DESCREVE.
 *
 * ═══ POR QUE ISTO EXISTE — um defeito meu, medido ═══════════════════════
 *
 * O filtro de categoria comparava `categoria ilike '%termo%'` contra o valor
 * GRAVADO, que é inglês. Digitando "mecanica", a busca não trazia "Auto repair
 * shop": `ilike` compara letra a letra e "mecanica" não é substring de "auto
 * repair shop". Eu anunciei o contrário no PR — e estávamos errados.
 *
 * Aqui o termo é convertido de volta para os valores em inglês que ele
 * descreve, e a API filtra por `in`. O operador digita português e o banco,
 * que é inglês, é filtrado certo.
 *
 * São DOIS passos, e a ordem não é estilo — é que a comparação do rótulo em
 * português é FLEXÍVEL (tira a vogal final) e a do valor gravado é crua:
 *
 * 1. **Rótulo em português, flexível** — "mecanica" acha "Oficina mecânica" e
 *    "Mecânico", porque a flexão de gênero é a flexão mais comum do português.
 * 2. **Valor gravado, cru** — quem digita "auto repair" ainda acha. É o idioma
 *    da origem: não é feio, é o que existe no dado.
 *
 * Houve aqui um terceiro passo, "tradução exata", que era **REDUNDANTE**: o
 * conjunto que ele produzia era sempre subconjunto do do passo 1. A mutação
 * que o desligou passou verde — e a leitura honesta é que ele nunca fez nada.
 *igualdade-primeiro era uma ideia razoável sobre ordenação, não uma
 * propriedade do resultado; o que segurava a lista curta era o filtro ser por
 * CATEGORIA, não o passo vir antes.
 *
 * Devolve lista vazia quando nada casa — e a API, nesse caso, não filtra por
 * categoria em vez de devolver zero. Um filtro que não acha é irritante; um
 * filtro que apaga a lista sem dizer por quê é um bug.
 */
/**
 * Comparações em português precisam de FLEXÃO, não de substring crua.
 *
 * O caso que mediu: o operador digita **"mecanica"** (adjetivo, sem acento, sem
 * o "o" final — é o que sai do teclado). A categoria se chama **"Mecânico"**.
 * `semAcento("mecanico").includes("mecanica")` é FALSO: "mecanic" vs "mecanic-o".
 * Sem isto, a busca achava "Oficina mecânica" e não achava "Mecânico" — que é
 * a mesma oficina com outra palavra.
 *
 * A regra é o mínimo que resolve a flexão de gênero, que é a mais comum em
 * português: tira uma vogal final. Não é stemming de verdade e não tenta ser —
 * "mecânica"/"mecânico", "loja"/"lojas" e "restaurante"/"restaurantes" caem;
 * "padaria"/"padeiro" continua fora, e está tudo bem.
 *
 * Só a comparação FLEXÍVEL usa isto. A igualdade exata do passo 1 usa
 * `semAcento`, porque "Oficina" e "Oficina mecânica" precisam continuar
 * diferentes — senão o filtro "oficina exata" puxa o catálogo inteiro.
 */
function semAcentoFlexivel(v: string): string {
  const base = semAcento(v);
  return base.replace(/(os|as|o|a)$/, "");
}

